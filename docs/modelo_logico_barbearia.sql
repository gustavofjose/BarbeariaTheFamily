-- 9.6 Movimento de caixa já consolidado em fechamento não pode ser alterado (RN14)
CREATE OR REPLACE FUNCTION fn_protege_movimento_caixa() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Movimentos de caixa não podem ser excluídos; lance um estorno.';
    END IF;
    IF OLD.id_fechamento IS NOT NULL THEN
        RAISE EXCEPTION 'Movimento % pertence a caixa fechado; corrija por estorno/novo lançamento.', OLD.id_movimento;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_mov_caixa_protegido
    BEFORE UPDATE OR DELETE ON movimento_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_protege_movimento_caixa();

/* =============================================================================
   10. VISÃO ÚTIL: SALDO DE ESTOQUE (derivado do razão)
   ============================================================================= */

CREATE OR REPLACE VIEW vw_saldo_estoque AS
SELECT p.id_produto,
       p.nome,
       p.unidade_medida,
       COALESCE(SUM(CASE m.tipo WHEN 'Entrada' THEN m.quantidade
                                WHEN 'Saida'   THEN -m.quantidade
                                ELSE 0 END), 0) AS saldo_sem_ajustes,
       p.estoque_minimo
FROM produto p
LEFT JOIN movimento_estoque m ON m.id_produto = p.id_produto
GROUP BY p.id_produto, p.nome, p.unidade_medida, p.estoque_minimo;
COMMENT ON VIEW vw_saldo_estoque IS 'Ajuste não tem sinal próprio na tabela; se a política exigir ajuste positivo/negativo, adicionar coluna de direção.';

