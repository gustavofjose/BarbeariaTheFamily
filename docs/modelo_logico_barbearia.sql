-- 9.1 Horário do agendamento dentro do expediente da regra referenciada (RN04)
CREATE OR REPLACE FUNCTION fn_valida_agendamento_calendario() RETURNS trigger AS $$
DECLARE
    r regra_calendario%ROWTYPE;
BEGIN
    SELECT * INTO r FROM regra_calendario WHERE id_regra_calendario = NEW.id_regra_calendario;

    IF r.situacao <> 'ABERTO' THEN
        RAISE EXCEPTION 'A regra de calendário % está FECHADA para esta data.', r.id_regra_calendario;
    END IF;
    IF NEW.data < r.vigencia_inicio OR (r.vigencia_fim IS NOT NULL AND NEW.data > r.vigencia_fim) THEN
        RAISE EXCEPTION 'A regra de calendário % não está vigente em %.', r.id_regra_calendario, NEW.data;
    END IF;
    IF r.tipo_regra = 'SEMANAL' AND EXTRACT(ISODOW FROM NEW.data)::int <> r.dia_semana THEN
        RAISE EXCEPTION 'A data % não corresponde ao dia da semana da regra.', NEW.data;
    END IF;
    IF r.tipo_regra = 'EXCECAO' AND NEW.data <> r.data_especifica THEN
        RAISE EXCEPTION 'A data % não corresponde à exceção de calendário.', NEW.data;
    END IF;
    IF NEW.hora_inicio < r.hora_abertura OR NEW.hora_fim > r.hora_fechamento THEN
        RAISE EXCEPTION 'Horário %–% fora do expediente (%–%).',
            NEW.hora_inicio, NEW.hora_fim, r.hora_abertura, r.hora_fechamento;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_agendamento_calendario
    BEFORE INSERT OR UPDATE OF data, hora_inicio, hora_fim, id_regra_calendario ON agendamento
    FOR EACH ROW EXECUTE FUNCTION fn_valida_agendamento_calendario();

-- 9.2 Só confirmar com ao menos um serviço e total pago (RN11)
CREATE OR REPLACE FUNCTION fn_valida_confirmacao_agendamento() RETURNS trigger AS $$
DECLARE
    v_servicos  INTEGER;
    v_total     NUMERIC(10,2);
    v_pago      NUMERIC(10,2);
BEGIN
    IF NEW.status = 'Confirmado' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'Confirmado') THEN
        SELECT count(*) INTO v_servicos FROM agendamento_servico WHERE id_agendamento = NEW.id_agendamento;
        IF v_servicos = 0 THEN
            RAISE EXCEPTION 'Agendamento % não pode ser confirmado sem ao menos um serviço.', NEW.id_agendamento;
        END IF;

        SELECT COALESCE((SELECT sum(preco_contratado) FROM agendamento_servico WHERE id_agendamento = NEW.id_agendamento), 0)
             + COALESCE((SELECT sum(preco_contratado) FROM agendamento_extra   WHERE id_agendamento = NEW.id_agendamento), 0)
          INTO v_total;

        SELECT COALESCE(sum(CASE WHEN tipo_operacao = 'Cobranca' THEN valor ELSE -valor END), 0)
          INTO v_pago
          FROM pagamento
         WHERE id_agendamento = NEW.id_agendamento AND status = 'Pago';

        IF v_pago < v_total THEN
            RAISE EXCEPTION 'Agendamento %: pagamento aprovado (%) menor que o total devido (%).',
                NEW.id_agendamento, v_pago, v_total;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_agendamento_confirmacao
    BEFORE UPDATE OF status ON agendamento
    FOR EACH ROW EXECUTE FUNCTION fn_valida_confirmacao_agendamento();

-- 9.3 Avaliação somente após atendimento concluído
CREATE OR REPLACE FUNCTION fn_valida_avaliacao() RETURNS trigger AS $$
DECLARE
    v_status VARCHAR(30);
BEGIN
    SELECT status INTO v_status FROM agendamento WHERE id_agendamento = NEW.id_agendamento;
    IF v_status IS DISTINCT FROM 'Concluido' THEN
        RAISE EXCEPTION 'Só é possível avaliar agendamentos Concluídos (status atual: %).', v_status;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_avaliacao_concluido
    BEFORE INSERT ON avaliacao
    FOR EACH ROW EXECUTE FUNCTION fn_valida_avaliacao();

-- 9.4 Estorno de pagamento só aponta para cobrança aprovada
CREATE OR REPLACE FUNCTION fn_valida_estorno() RETURNS trigger AS $$
DECLARE
    o pagamento%ROWTYPE;
BEGIN
    IF NEW.tipo_operacao = 'Estorno' THEN
        SELECT * INTO o FROM pagamento WHERE id_pagamento = NEW.id_pagamento_origem;
        IF o.tipo_operacao <> 'Cobranca' OR o.status <> 'Pago' THEN
            RAISE EXCEPTION 'Estorno deve referenciar uma cobrança com status Pago.';
        END IF;
        IF o.id_agendamento <> NEW.id_agendamento THEN
            RAISE EXCEPTION 'Estorno e cobrança de origem devem pertencer ao mesmo agendamento.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pagamento_estorno
    BEFORE INSERT OR UPDATE OF tipo_operacao, id_pagamento_origem, id_agendamento ON pagamento
    FOR EACH ROW EXECUTE FUNCTION fn_valida_estorno();

