CREATE TABLE fechamento_caixa (
    id_fechamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    INTEGER       NOT NULL,
    aberto_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fechado_em    TIMESTAMPTZ,
    saldo_abertura NUMERIC(10,2) NOT NULL DEFAULT 0,
    status        VARCHAR(15)   NOT NULL DEFAULT 'Aberto',
    CONSTRAINT fk_fech_usuario FOREIGN KEY (id_usuario) REFERENCES usuario_sistema (id_usuario),
    CONSTRAINT ck_fech_status  CHECK (status IN ('Aberto','Fechado')),
    CONSTRAINT ck_fech_saldo   CHECK (saldo_abertura >= 0),
    CONSTRAINT ck_fech_datas   CHECK (
        (status = 'Aberto'  AND fechado_em IS NULL) OR
        (status = 'Fechado' AND fechado_em IS NOT NULL AND fechado_em >= aberto_em)
    )
);
