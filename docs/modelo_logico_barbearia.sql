/* =============================================================================
   MODELO LÓGICO — Barbearia The Family Hair
   Fonte: Dicionário de Dados (25 tabelas: 20 entidades + 5 associativas)
   SGBD : PostgreSQL 15+  (UTF-8)
   Convenções: nomes em minúsculas com underscore; valores monetários em
               NUMERIC(10,2); instantes em TIMESTAMPTZ; domínios fechados via
               CHECK; desativar em vez de excluir (RN08).
   Observação: formas de pagamento padronizadas sem acento e sem espaço
               ('Pix','Credito','Debito','Dinheiro') para uso em CHECK.
