CREATE TABLE agendamento (
    id_agendamento          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente              INTEGER      NOT NULL,
    id_profissional         INTEGER      NOT NULL,
    id_regra_calendario     INTEGER      NOT NULL,
    data                    DATE         NOT NULL,
    hora_inicio             TIME         NOT NULL,
    hora_fim                TIME         NOT NULL,
    status                  VARCHAR(30)  NOT NULL DEFAULT 'Aguardando_pagamento',
    politica_reserva_versao VARCHAR(30)  NOT NULL,
    politica_aceita_em      TIMESTAMPTZ  NOT NULL,
    criado_em               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_em               TIMESTAMPTZ,
    confirmado_em           TIMESTAMPTZ,
    checkin_em              TIMESTAMPTZ,
    cancelado_em            TIMESTAMPTZ,
    motivo_cancelamento     VARCHAR(255),
    observacao              VARCHAR(255),
    CONSTRAINT fk_agend_cliente  FOREIGN KEY (id_cliente)          REFERENCES cliente (id_cliente),
    CONSTRAINT fk_agend_prof     FOREIGN KEY (id_profissional)     REFERENCES profissional (id_profissional),
    CONSTRAINT fk_agend_regra    FOREIGN KEY (id_regra_calendario) REFERENCES regra_calendario (id_regra_calendario),
    CONSTRAINT ck_agend_status CHECK (status IN ('Aguardando_pagamento','Confirmado','Concluido','Cancelado','Faltou')),
    CONSTRAINT ck_agend_horas  CHECK (hora_fim > hora_inicio),
    CONSTRAINT ck_agend_expira CHECK (status <> 'Aguardando_pagamento' OR expira_em IS NOT NULL),
    CONSTRAINT ck_agend_confirmado CHECK (status NOT IN ('Confirmado','Concluido','Faltou') OR confirmado_em IS NOT NULL),
    CONSTRAINT ck_agend_cancelado  CHECK (status <> 'Cancelado' OR cancelado_em IS NOT NULL),
    -- RN09: um profissional não pode ter agendamentos sobrepostos (exceto cancelados)
    CONSTRAINT ex_agend_sem_sobreposicao EXCLUDE USING gist (
        id_profissional WITH =,
        tsrange((data + hora_inicio), (data + hora_fim)) WITH &&
    ) WHERE (status <> 'Cancelado')
);
CREATE INDEX ix_agend_prof_data_hora ON agendamento (id_profissional, data, hora_inicio);
CREATE INDEX ix_agend_cliente        ON agendamento (id_cliente);
CREATE INDEX ix_agend_regra          ON agendamento (id_regra_calendario);
CREATE INDEX ix_agend_status         ON agendamento (status);

CREATE TABLE agendamento_servico (
    id_agendamento     INTEGER       NOT NULL,
    id_servico         INTEGER       NOT NULL,
    preco_contratado   NUMERIC(10,2) NOT NULL,
    duracao_contratada SMALLINT      NOT NULL,
    PRIMARY KEY (id_agendamento, id_servico),
    CONSTRAINT fk_ags_agend   FOREIGN KEY (id_agendamento) REFERENCES agendamento (id_agendamento),
    CONSTRAINT fk_ags_servico FOREIGN KEY (id_servico)     REFERENCES servico (id_servico),
    CONSTRAINT ck_ags_preco   CHECK (preco_contratado >= 0),
    CONSTRAINT ck_ags_duracao CHECK (duracao_contratada > 0)
);
CREATE INDEX ix_ags_servico ON agendamento_servico (id_servico);

CREATE TABLE agendamento_extra (
    id_agendamento     INTEGER       NOT NULL,
    id_extra           INTEGER       NOT NULL,
    preco_contratado   NUMERIC(10,2) NOT NULL,
    duracao_contratada SMALLINT      NOT NULL,
    PRIMARY KEY (id_agendamento, id_extra),
    CONSTRAINT fk_age_agend FOREIGN KEY (id_agendamento) REFERENCES agendamento (id_agendamento),
    CONSTRAINT fk_age_extra FOREIGN KEY (id_extra)       REFERENCES servico_extra (id_extra),
    CONSTRAINT ck_age_preco   CHECK (preco_contratado >= 0),
    CONSTRAINT ck_age_duracao CHECK (duracao_contratada >= 0)
);
CREATE INDEX ix_age_extra ON agendamento_extra (id_extra);

CREATE TABLE pagamento (
    id_pagamento        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agendamento      INTEGER       NOT NULL,       -- FK não UNIQUE: retentativas e estornos
    id_pagamento_origem INTEGER,
    tipo_operacao       VARCHAR(20)   NOT NULL,
    forma_pagamento     VARCHAR(30)   NOT NULL,
    valor               NUMERIC(10,2) NOT NULL,
    status              VARCHAR(30)   NOT NULL,
    criado_em           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    confirmado_em       TIMESTAMPTZ,
    referencia_provedor VARCHAR(100),
    chave_idempotencia  VARCHAR(100),
    CONSTRAINT fk_pag_agend  FOREIGN KEY (id_agendamento)      REFERENCES agendamento (id_agendamento),
    CONSTRAINT fk_pag_origem FOREIGN KEY (id_pagamento_origem) REFERENCES pagamento (id_pagamento),
    CONSTRAINT ck_pag_tipo   CHECK (tipo_operacao IN ('Cobranca','Estorno')),
    CONSTRAINT ck_pag_forma  CHECK (forma_pagamento IN ('Pix','Credito','Debito','Dinheiro')),
    CONSTRAINT ck_pag_status CHECK (status IN ('Pendente','Pago','Falhou')),
    CONSTRAINT ck_pag_valor  CHECK (valor > 0),
    CONSTRAINT ck_pag_confirmado CHECK (status <> 'Pago' OR confirmado_em IS NOT NULL),
    -- Estorno aponta para a cobrança original; cobrança não aponta
    CONSTRAINT ck_pag_estorno_origem CHECK (
        (tipo_operacao = 'Estorno'  AND id_pagamento_origem IS NOT NULL) OR
        (tipo_operacao = 'Cobranca' AND id_pagamento_origem IS NULL)
    )
);
CREATE INDEX ix_pag_agend_status  ON pagamento (id_agendamento, status);
CREATE INDEX ix_pag_status_criado ON pagamento (status, criado_em);
CREATE INDEX ix_pag_origem        ON pagamento (id_pagamento_origem);
CREATE UNIQUE INDEX uq_pag_referencia_provedor ON pagamento (referencia_provedor) WHERE referencia_provedor IS NOT NULL;
CREATE UNIQUE INDEX uq_pag_idempotencia        ON pagamento (chave_idempotencia)  WHERE chave_idempotencia  IS NOT NULL;
COMMENT ON TABLE pagamento IS 'Tentativas, capturas e estornos. Nunca armazenar número de cartão, CVV, senha ou token.';

CREATE TABLE avaliacao (
    id_avaliacao   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agendamento INTEGER      NOT NULL,
    nota           INTEGER      NOT NULL,
    comentario     VARCHAR(500),
    data_avaliacao TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_avaliacao_agend UNIQUE (id_agendamento),          -- (0,1) por agendamento
    CONSTRAINT fk_aval_agend FOREIGN KEY (id_agendamento) REFERENCES agendamento (id_agendamento),
    CONSTRAINT ck_aval_nota  CHECK (nota BETWEEN 1 AND 5)
);

/* =============================================================================
   4. PRODUTOS, FORNECEDORES, COMPRAS E VENDAS
