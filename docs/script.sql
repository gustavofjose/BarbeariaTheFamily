-- Barbearia The Family Hair - conversão para PostgreSQL 15+
-- O script cria um schema próprio e não apaga bancos existentes.
BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS barbearia;
SET search_path TO barbearia, public;

CREATE TABLE cliente (
  id_cliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  telefone varchar(20) NOT NULL,
  email varchar(100),
  data_cadastro timestamptz NOT NULL DEFAULT now(),
  data_atualizacao timestamptz,
  ativo boolean NOT NULL DEFAULT true,
  aceita_marketing boolean NOT NULL DEFAULT false,
  data_consentimento_marketing timestamptz,
  CONSTRAINT ck_cliente_email CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  CONSTRAINT ck_cliente_consentimento CHECK (NOT aceita_marketing OR data_consentimento_marketing IS NOT NULL)
);

CREATE TABLE profissional (
  id_profissional integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  especialidade varchar(100),
  telefone varchar(20),
  ativo boolean NOT NULL DEFAULT true
);

CREATE TABLE servico (
  id_servico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  descricao varchar(255),
  duracao integer NOT NULL CHECK (duracao > 0),
  preco numeric(10,2) NOT NULL CHECK (preco >= 0),
  ativo boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX uq_servico_nome_ativo ON servico (lower(nome)) WHERE ativo;

CREATE TABLE servico_extra (
  id_extra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  descricao varchar(255),
  preco numeric(10,2) NOT NULL CHECK (preco >= 0),
  duracao integer NOT NULL CHECK (duracao >= 0),
  ativo boolean NOT NULL DEFAULT true
);

CREATE TABLE usuario_sistema (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_exibicao varchar(100) NOT NULL,
  identificador_login varchar(150) NOT NULL UNIQUE,
  perfil varchar(30) NOT NULL CHECK (perfil IN ('Administrador','Atendimento','Profissional')),
  ativo boolean NOT NULL DEFAULT true,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  data_desativacao timestamptz,
  CONSTRAINT ck_usuario_desativacao CHECK ((ativo AND data_desativacao IS NULL) OR (NOT ativo AND data_desativacao IS NOT NULL))
);

CREATE TABLE log_auditoria (
  id_log bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario),
  data_hora timestamptz NOT NULL DEFAULT now(),
  acao varchar(40) NOT NULL CHECK (acao IN ('LOGIN','LOGIN_FALHA','CONSULTA','DML','DDL','ALTERACAO_PERMISSAO','EXPORTACAO','ESTORNO')),
  componente varchar(20) NOT NULL CHECK (componente IN ('APLICACAO','SGBD')),
  recurso varchar(60) NOT NULL,
  resultado varchar(20) NOT NULL CHECK (resultado IN ('SUCESSO','FALHA')),
  identificador_registro varchar(100), origem varchar(100), principal_sgbd varchar(100),
  id_sessao_sgbd varchar(100), id_correlacao varchar(64), data_expurgo_prevista date NOT NULL
);

CREATE TABLE produto (
  id_produto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(120) NOT NULL,
  tipo_produto varchar(15) NOT NULL CHECK (tipo_produto IN ('Revenda','Insumo','Ambos')),
  unidade_medida varchar(15) NOT NULL,
  sku varchar(50), descricao varchar(255),
  preco_venda numeric(10,2), ativo boolean NOT NULL DEFAULT true,
  estoque_minimo numeric(10,3),
  CONSTRAINT ck_produto_preco CHECK ((tipo_produto = 'Insumo' OR preco_venda IS NOT NULL) AND (preco_venda IS NULL OR preco_venda >= 0)),
  CONSTRAINT ck_produto_minimo CHECK (estoque_minimo IS NULL OR estoque_minimo >= 0)
);
CREATE UNIQUE INDEX uq_produto_sku ON produto(sku) WHERE sku IS NOT NULL;

CREATE TABLE fornecedor (
  id_fornecedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_razao_social varchar(150) NOT NULL,
  documento_fiscal varchar(20), telefone varchar(20), email varchar(150), ativo boolean NOT NULL DEFAULT true,
  CONSTRAINT ck_fornecedor_email CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);
CREATE UNIQUE INDEX uq_fornecedor_documento ON fornecedor(documento_fiscal) WHERE documento_fiscal IS NOT NULL;

CREATE TABLE compra (
  id_compra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fornecedor integer NOT NULL REFERENCES fornecedor(id_fornecedor),
  id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario),
  data_pedido timestamptz NOT NULL DEFAULT now(), status varchar(20) NOT NULL DEFAULT 'Rascunho',
  data_recebimento timestamptz, valor_total numeric(10,2) NOT NULL DEFAULT 0, observacao varchar(255),
  CHECK (status IN ('Rascunho','Pedida','Recebida','Cancelada')),
  CHECK (status <> 'Recebida' OR data_recebimento IS NOT NULL), CHECK (valor_total >= 0)
);

CREATE TABLE item_compra (
  id_compra integer NOT NULL REFERENCES compra(id_compra), id_produto integer NOT NULL REFERENCES produto(id_produto),
  quantidade numeric(10,3) NOT NULL CHECK (quantidade > 0), custo_unitario numeric(10,2) NOT NULL CHECK (custo_unitario >= 0),
  PRIMARY KEY (id_compra, id_produto)
);

CREATE TABLE venda (
  id_venda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario), id_cliente integer REFERENCES cliente(id_cliente),
  data_hora timestamptz NOT NULL DEFAULT now(), status varchar(20) NOT NULL DEFAULT 'Aberta', valor_total numeric(10,2) NOT NULL DEFAULT 0,
  forma_pagamento varchar(30), CHECK (status IN ('Aberta','Concluida','Cancelada')), CHECK (valor_total >= 0),
  CHECK (forma_pagamento IS NULL OR forma_pagamento IN ('Pix','Credito','Debito','Dinheiro')),
  CHECK (status <> 'Concluida' OR forma_pagamento IS NOT NULL)
);

CREATE TABLE item_venda (
  id_venda integer NOT NULL REFERENCES venda(id_venda), id_produto integer NOT NULL REFERENCES produto(id_produto),
  quantidade numeric(10,3) NOT NULL CHECK (quantidade > 0), preco_unitario numeric(10,2) NOT NULL CHECK (preco_unitario >= 0),
  desconto_unitario numeric(10,2) CHECK (desconto_unitario IS NULL OR (desconto_unitario >= 0 AND desconto_unitario <= preco_unitario)),
  PRIMARY KEY (id_venda, id_produto)
);

CREATE TABLE conta_pagar (
  id_conta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fornecedor integer REFERENCES fornecedor(id_fornecedor), id_compra integer REFERENCES compra(id_compra),
  id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario), descricao varchar(150) NOT NULL, categoria varchar(40) NOT NULL,
  valor numeric(10,2) NOT NULL CHECK (valor > 0), data_vencimento date NOT NULL, status varchar(20) NOT NULL DEFAULT 'Aberta', data_baixa timestamptz,
  CHECK (status IN ('Aberta','Paga','Atrasada','Cancelada')), CHECK (status <> 'Paga' OR data_baixa IS NOT NULL)
);

CREATE TABLE fechamento_caixa (
  id_fechamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario), aberto_em timestamptz NOT NULL DEFAULT now(), fechado_em timestamptz,
  saldo_abertura numeric(10,2) NOT NULL DEFAULT 0 CHECK (saldo_abertura >= 0), status varchar(15) NOT NULL DEFAULT 'Aberto',
  CHECK (status IN ('Aberto','Fechado')),
  CHECK ((status = 'Aberto' AND fechado_em IS NULL) OR (status = 'Fechado' AND fechado_em IS NOT NULL AND fechado_em >= aberto_em))
);
CREATE UNIQUE INDEX uq_fechamento_um_aberto ON fechamento_caixa(status) WHERE status = 'Aberto';

CREATE TABLE fechamento_forma (
  id_fechamento integer NOT NULL REFERENCES fechamento_caixa(id_fechamento), forma_pagamento varchar(20) NOT NULL,
  valor_esperado numeric(10,2) NOT NULL, valor_conferido numeric(10,2) NOT NULL,
  diferenca numeric(10,2) GENERATED ALWAYS AS (valor_conferido - valor_esperado) STORED,
  CHECK (forma_pagamento IN ('Pix','Credito','Debito','Dinheiro')), PRIMARY KEY (id_fechamento, forma_pagamento)
);

CREATE TABLE regra_calendario (
  id_regra_calendario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_regra varchar(15) NOT NULL CHECK (tipo_regra IN ('SEMANAL','EXCECAO')),
  dia_semana smallint, data_especifica date, situacao varchar(10) NOT NULL CHECK (situacao IN ('ABERTO','FECHADO')),
  hora_abertura time, hora_fechamento time, vigencia_inicio date NOT NULL, vigencia_fim date, motivo varchar(120), ativo boolean NOT NULL DEFAULT true,
  CHECK ((tipo_regra = 'SEMANAL' AND dia_semana BETWEEN 1 AND 7 AND data_especifica IS NULL) OR (tipo_regra = 'EXCECAO' AND dia_semana IS NULL AND data_especifica IS NOT NULL)),
  CHECK ((situacao = 'ABERTO' AND hora_abertura IS NOT NULL AND hora_fechamento > hora_abertura) OR (situacao = 'FECHADO' AND hora_abertura IS NULL AND hora_fechamento IS NULL)),
  CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio)
);
CREATE UNIQUE INDEX uq_regra_excecao_data ON regra_calendario(data_especifica) WHERE tipo_regra = 'EXCECAO' AND ativo;
CREATE UNIQUE INDEX uq_regra_semanal_vigencia ON regra_calendario(dia_semana, vigencia_inicio) WHERE tipo_regra = 'SEMANAL' AND ativo;

CREATE TABLE agendamento (
  id_agendamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NOT NULL REFERENCES cliente(id_cliente), id_profissional integer NOT NULL REFERENCES profissional(id_profissional),
  id_regra_calendario integer NOT NULL REFERENCES regra_calendario(id_regra_calendario), data date NOT NULL, hora_inicio time NOT NULL, hora_fim time NOT NULL,
  status varchar(30) NOT NULL DEFAULT 'Aguardando_pagamento', politica_reserva_versao varchar(30) NOT NULL, politica_aceita_em timestamptz NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now(), expira_em timestamptz, confirmado_em timestamptz, checkin_em timestamptz, cancelado_em timestamptz,
  motivo_cancelamento varchar(255), observacao varchar(255), CHECK (hora_fim > hora_inicio),
  CHECK (status IN ('Aguardando_pagamento','Confirmado','Concluido','Cancelado','Faltou')),
  CHECK (status <> 'Aguardando_pagamento' OR expira_em IS NOT NULL), CHECK (status NOT IN ('Confirmado','Concluido','Faltou') OR confirmado_em IS NOT NULL),
  CHECK (status <> 'Cancelado' OR cancelado_em IS NOT NULL),
  CONSTRAINT ex_agendamento_sem_sobreposicao EXCLUDE USING gist (id_profissional WITH =, tsrange(data + hora_inicio, data + hora_fim) WITH &&) WHERE (status <> 'Cancelado')
);

CREATE TABLE agendamento_servico (
  id_agendamento integer NOT NULL REFERENCES agendamento(id_agendamento), id_servico integer NOT NULL REFERENCES servico(id_servico),
  preco_contratado numeric(10,2) NOT NULL CHECK (preco_contratado >= 0), duracao_contratada smallint NOT NULL CHECK (duracao_contratada > 0), PRIMARY KEY (id_agendamento,id_servico)
);
CREATE TABLE agendamento_extra (
  id_agendamento integer NOT NULL REFERENCES agendamento(id_agendamento), id_extra integer NOT NULL REFERENCES servico_extra(id_extra),
  preco_contratado numeric(10,2) NOT NULL CHECK (preco_contratado >= 0), duracao_contratada smallint NOT NULL CHECK (duracao_contratada >= 0), PRIMARY KEY (id_agendamento,id_extra)
);

CREATE TABLE pagamento (
  id_pagamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_agendamento integer NOT NULL REFERENCES agendamento(id_agendamento), id_pagamento_origem integer REFERENCES pagamento(id_pagamento),
  tipo_operacao varchar(20) NOT NULL CHECK (tipo_operacao IN ('Cobranca','Estorno')), forma_pagamento varchar(30) NOT NULL CHECK (forma_pagamento IN ('Pix','Credito','Debito','Dinheiro')),
  valor numeric(10,2) NOT NULL CHECK (valor > 0), status varchar(30) NOT NULL CHECK (status IN ('Pendente','Pago','Falhou')), criado_em timestamptz NOT NULL DEFAULT now(), confirmado_em timestamptz,
  referencia_provedor varchar(100), chave_idempotencia varchar(100), CHECK ((tipo_operacao = 'Estorno') = (id_pagamento_origem IS NOT NULL)), CHECK (status <> 'Pago' OR confirmado_em IS NOT NULL)
);
CREATE UNIQUE INDEX uq_pagamento_referencia ON pagamento(referencia_provedor) WHERE referencia_provedor IS NOT NULL;
CREATE UNIQUE INDEX uq_pagamento_idempotencia ON pagamento(chave_idempotencia) WHERE chave_idempotencia IS NOT NULL;

CREATE TABLE avaliacao (
  id_avaliacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_agendamento integer NOT NULL UNIQUE REFERENCES agendamento(id_agendamento),
  nota integer NOT NULL CHECK (nota BETWEEN 1 AND 5), comentario varchar(500), data_avaliacao timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE registro_higienizacao (
  id_registro bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario), data_hora timestamptz NOT NULL DEFAULT now(),
  item_area varchar(100) NOT NULL, etapa varchar(20) NOT NULL CHECK (etapa IN ('Limpeza','Desinfeccao','Esterilizacao','Descarte')),
  metodo varchar(120) NOT NULL, produto_lote varchar(100), referencia_ciclo varchar(100), resultado varchar(20) NOT NULL CHECK (resultado IN ('Aprovado','Reprovado')), observacao varchar(255)
);

CREATE TABLE movimento_caixa (
  id_movimento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario),
  id_pagamento integer REFERENCES pagamento(id_pagamento), id_venda integer REFERENCES venda(id_venda), id_conta integer REFERENCES conta_pagar(id_conta), id_fechamento integer REFERENCES fechamento_caixa(id_fechamento),
  tipo varchar(20) NOT NULL CHECK (tipo IN ('Entrada','Saida','Estorno','Ajuste')), forma_pagamento varchar(20) NOT NULL CHECK (forma_pagamento IN ('Pix','Credito','Debito','Dinheiro','Nao_aplicavel')),
  valor numeric(10,2) NOT NULL CHECK (valor > 0), data_hora timestamptz NOT NULL DEFAULT now(), motivo varchar(255),
  CHECK ((id_pagamento IS NOT NULL)::int + (id_venda IS NOT NULL)::int + (id_conta IS NOT NULL)::int <= 1),
  CHECK (tipo = 'Ajuste' OR (id_pagamento IS NOT NULL)::int + (id_venda IS NOT NULL)::int + (id_conta IS NOT NULL)::int = 1),
  CHECK (tipo NOT IN ('Ajuste','Estorno') OR motivo IS NOT NULL)
);

CREATE TABLE movimento_estoque (
  id_mov_estoque bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_produto integer NOT NULL REFERENCES produto(id_produto), id_usuario integer NOT NULL REFERENCES usuario_sistema(id_usuario),
  id_compra integer, id_venda integer, id_registro_higienizacao bigint REFERENCES registro_higienizacao(id_registro), tipo varchar(15) NOT NULL CHECK (tipo IN ('Entrada','Saida','Ajuste')),
  quantidade numeric(10,3) NOT NULL CHECK (quantidade > 0), custo_unitario numeric(10,4) CHECK (custo_unitario IS NULL OR custo_unitario >= 0), data_hora timestamptz NOT NULL DEFAULT now(), motivo varchar(255),
  FOREIGN KEY (id_compra, id_produto) REFERENCES item_compra(id_compra, id_produto), FOREIGN KEY (id_venda, id_produto) REFERENCES item_venda(id_venda, id_produto),
  CHECK ((tipo = 'Entrada' AND id_venda IS NULL AND id_registro_higienizacao IS NULL) OR (tipo = 'Saida' AND id_compra IS NULL AND ((id_venda IS NOT NULL)::int + (id_registro_higienizacao IS NOT NULL)::int <= 1)) OR (tipo = 'Ajuste' AND id_compra IS NULL AND id_venda IS NULL AND id_registro_higienizacao IS NULL AND motivo IS NOT NULL))
);

CREATE TABLE documento_fiscal (
  id_documento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_agendamento integer REFERENCES agendamento(id_agendamento), id_venda integer REFERENCES venda(id_venda), id_compra integer REFERENCES compra(id_compra),
  tipo varchar(30) NOT NULL, numero varchar(30) NOT NULL, serie varchar(20), chave_acesso varchar(60), emitido_em timestamptz NOT NULL, status varchar(20) NOT NULL, localizador_arquivo varchar(255),
  CHECK ((id_agendamento IS NOT NULL)::int + (id_venda IS NOT NULL)::int + (id_compra IS NOT NULL)::int = 1)
);
CREATE UNIQUE INDEX uq_documento_fiscal_numero ON documento_fiscal(tipo, coalesce(serie,''), numero);
CREATE UNIQUE INDEX uq_documento_fiscal_chave ON documento_fiscal(chave_acesso) WHERE chave_acesso IS NOT NULL;

CREATE OR REPLACE VIEW vw_saldo_estoque AS
SELECT p.id_produto, p.nome, p.unidade_medida,
       COALESCE(sum(CASE m.tipo WHEN 'Entrada' THEN m.quantidade WHEN 'Saida' THEN -m.quantidade ELSE 0 END), 0) AS saldo,
       p.estoque_minimo
FROM produto p LEFT JOIN movimento_estoque m ON m.id_produto = p.id_produto
GROUP BY p.id_produto, p.nome, p.unidade_medida, p.estoque_minimo;

COMMIT;
